<?php
declare(strict_types=1);

namespace App\Service;

use App\Service\Branding\BrandingImageException;
use App\Service\Branding\IcoWriter;
use Cake\Core\Configure;
use Cake\ORM\Locator\LocatorAwareTrait;
use GdImage;
use Psr\Http\Message\UploadedFileInterface;
use Throwable;

/**
 * The site's logo and favicon.
 *
 * Both live on disk under webroot/img/branding, never in the database. They are
 * on every single page, including the public scoreboard players leave open all
 * day, so they have to be served by the web server straight from a file the way
 * any other static asset is, without a PHP request or a blob read behind them.
 *
 * The `config` table therefore stores only a choice: the slug of one of the
 * shipped presets, or `custom` for artwork an administrator uploaded. Uploads
 * are re-encoded rather than moved into place, so the file that ends up in
 * webroot is always one GD produced from pixels it could actually decode.
 */
class BrandingService
{
    use LocatorAwareTrait;

    /**
     * `config` row holding the chosen logo.
     */
    public const PARAM_LOGO = 'brand_logo';

    /**
     * `config` row holding the chosen favicon.
     */
    public const PARAM_FAVICON = 'brand_favicon';

    /**
     * The slug that means "use the artwork an administrator uploaded".
     */
    public const CUSTOM = 'custom';

    /**
     * Fallback whenever the stored choice is missing or no longer exists.
     */
    public const DEFAULT_SLUG = 'dragon-crest';

    /**
     * Formats an administrator may upload, and what each is served as.
     *
     * The type is decided by decoding the file, never by the browser's
     * Content-Type header, which the client controls.
     *
     * @var array<int, string>
     */
    public const ALLOWED_TYPES = [
        IMAGETYPE_PNG => 'image/png',
        IMAGETYPE_JPEG => 'image/jpeg',
        IMAGETYPE_GIF => 'image/gif',
        IMAGETYPE_WEBP => 'image/webp',
    ];

    /**
     * Logo rules. The navbar scales the image to about 33 pixels tall and lets
     * it keep its own width, so anything from a square emblem to a fairly wide
     * wordmark works; something taller than it is wide does not.
     */
    public const LOGO_MIN_SIDE = 128;
    public const LOGO_MAX_SIDE = 2048;
    public const LOGO_MAX_BYTES = 2097152;
    public const LOGO_MIN_RATIO = 0.8;
    public const LOGO_MAX_RATIO = 3.0;

    /**
     * The size the stored logo is normalised to, on its longest side.
     */
    public const LOGO_STORED_SIDE = 512;

    /**
     * Favicon rules. A favicon is drawn at 16 pixels more often than not, so it
     * has to be square and it has to start out big enough that the downscale to
     * 16 still leaves something readable.
     */
    public const FAVICON_MIN_SIDE = 32;
    public const FAVICON_MAX_SIDE = 512;
    public const FAVICON_MAX_BYTES = 524288;

    /**
     * How far from square a favicon may be, as a fraction of its own width.
     *
     * Not zero: exporting a 64x63 icon from a drawing tool is a rounding
     * accident, not a different intention, and it is squared up on save.
     */
    public const FAVICON_RATIO_TOLERANCE = 0.1;

    /**
     * The square side the stored favicon PNG is normalised to.
     */
    public const FAVICON_STORED_SIDE = 256;

